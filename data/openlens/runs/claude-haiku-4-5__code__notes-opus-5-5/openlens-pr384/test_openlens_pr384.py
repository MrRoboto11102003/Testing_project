class TestOpticStudioExporter:
    """Test OpticStudioExporter.export_lens"""

    def test_export_lens_creates_file_with_header(self, tmp_path):
        """Test that export_lens creates file with correct header"""
        from openlens.export_formats import OpticStudioExporter
        from openlens.lens import Lens

        lens = Lens(
            name="TestLens",
            radius_of_curvature_1=50.0,
            radius_of_curvature_2=-50.0,
            thickness=5.0,
            diameter=25.0,
            material="BK7"
        )

        output_file = tmp_path / "lens.txt"
        OpticStudioExporter.export_lens(lens, str(output_file))

        assert output_file.exists()
        content = output_file.read_text(encoding="utf-8")
        lines = content.splitlines()

        assert lines[0] == "# OpenLens Export - OpticStudio Format"
        assert lines[1] == f"# Lens: TestLens"
        assert lines[2] == "#" + "=" * 60
        assert "SYSTEM PRESCRIPTION DATA" in content
        assert "Units: Millimeters" in content

    def test_export_lens_formats_numbers_correctly(self, tmp_path):
        """Test number formatting matches specification"""
        from openlens.export_formats import OpticStudioExporter
        from openlens.lens import Lens

        lens = Lens(
            name="L",
            radius_of_curvature_1=100.0,
            radius_of_curvature_2=-100.0,
            thickness=5.0,
            diameter=25.0,
            material="BK7",
            bevel_1=0.5,
            bevel_2=0.25
        )

        output_file = tmp_path / "lens.txt"
        OpticStudioExporter.export_lens(lens, str(output_file))

        content = output_file.read_text(encoding="utf-8")

        # Refractive index uses 6 decimals per spec
        assert f"Refractive Index (d-line): {lens.refractive_index:.6f}" in content
        # Bevel uses 4 decimals
        assert "Bevel 1/2 (45 deg): 0.5000 / 0.2500 mm" in content

    def test_export_system_includes_elements(self, tmp_path):
        """Test OpticStudioExporter.export_system"""
        from openlens.export_formats import OpticStudioExporter
        from openlens.optical_system import OpticalSystem
        from openlens.lens import Lens

        system = OpticalSystem(name="TestSystem")
        lens = Lens(
            name="L1",
            radius_of_curvature_1=50.0,
            radius_of_curvature_2=-50.0,
            thickness=5.0,
            diameter=25.0,
            material="BK7"
        )
        system.add_lens(lens)

        output_file = tmp_path / "system.txt"
        OpticStudioExporter.export_system(system, str(output_file))

        content = output_file.read_text(encoding="utf-8")

